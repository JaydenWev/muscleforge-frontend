#!/usr/bin/env python3
"""Generate the initial GET/status C# client from the pinned OpenAPI snapshot.

Generator version 1. Only parameterless GETs returning a required string-object
are supported. Unsupported contracts fail explicitly; extend or replace this
generator when authentication and exercise operations are added.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
VERSION = 1


def identifier(value):
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", value):
        raise ValueError(f"Unsupported C# identifier: {value}")
    return value[0].upper() + value[1:]


def generate(document):
    if document.get("security"):
        raise ValueError("Extend authentication generation before adding global security requirements")
    lines = [f"// <auto-generated> MuscleForge contract generator v{VERSION}. Do not edit. </auto-generated>",
             "#nullable enable", "using System.Net.Http.Json;", "using System.Text.Json;",
             "using System.Text.Json.Serialization;", "", "namespace MuscleForge.Client;", ""]
    methods = []
    for path, operations in sorted(document["paths"].items()):
        if not re.fullmatch(r"/[a-zA-Z0-9/_-]+", path):
            raise ValueError(f"Unsupported route: {path}")
        for method, operation in operations.items():
            if method != "get" or any(key in operation for key in ("parameters", "requestBody", "security")):
                raise ValueError("This generator only supports public parameterless GET operations")
            if set(operation["responses"]) != {"200"}:
                raise ValueError("Extend error-response generation before adding additional responses")
            schema = operation["responses"]["200"]["content"]["application/json"]["schema"]
            properties = schema["properties"]
            if schema["type"] != "object" or set(schema.get("required", [])) != set(properties):
                raise ValueError("Expected an object with required properties")
            if any(value != {"type": "string"} for value in properties.values()):
                raise ValueError("Extend DTO generation before adding non-string properties")
            operation_id = identifier(operation["operationId"])
            response_type = operation_id.removeprefix("Get") + "Response"
            lines.extend([f"public sealed class {response_type}", "{"])
            for name in sorted(properties):
                lines.extend([f'    [JsonPropertyName("{name}")]',
                              f"    public required string {identifier(name)} {{ get; init; }}", ""])
            lines.extend(["}", ""])
            methods.extend([
                f"    public async Task<{response_type}> {operation_id}Async(",
                "        Uri baseUrl, CancellationToken cancellationToken = default)", "    {",
                f'        var uri = new Uri(baseUrl, "{path.lstrip("/")}");',
                f"        return await httpClient.GetFromJsonAsync<{response_type}>(uri, cancellationToken)",
                "            .ConfigureAwait(false)",
                '            ?? throw new JsonException("The API returned an empty response.");',
                "    }", ""])
    lines.extend(["public sealed class MuscleForgeApiClient(HttpClient httpClient)", "{", *methods, "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = (ROOT / "contracts/openapi.json").read_bytes()
    source = json.loads((ROOT / "contracts/source.json").read_text())
    if not re.fullmatch(r"[0-9a-f]{40}", source.get("backendCommit") or ""):
        raise SystemExit("Pin an explicit backend commit in contracts/source.json")
    if hashlib.sha256(contract).hexdigest() != source["contractSha256"]:
        raise SystemExit("Contract hash does not match contracts/source.json")
    if source["generatorVersion"] != VERSION:
        raise SystemExit("Contract source expects a different generator version")
    output = generate(json.loads(contract))
    target = ROOT / "src/MuscleForge.Client/Generated/MuscleForgeApiClient.g.cs"
    if args.check:
        if not target.is_file() or target.read_text() != output:
            raise SystemExit("Generated-client drift: run python3 scripts/generate-api-client.py")
        print("Generated client and pinned contract hash match")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(output)
        print(f"Generated {target}")


if __name__ == "__main__":
    main()
